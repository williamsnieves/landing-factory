// Reading the i18n setup of a multi-locale site (add-bilingual-landing): the `i18n` block of astro.config.mjs, the UI
// dictionary src/i18n/ui.ts and the hreflang/language-switcher markup of a built page. Used by check-landing. A site
// without an `i18n` block is a single-language site and every function here reports "no i18n" for it.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const stripLineComments = (text) => text.replace(/^[ \t]*\/\/.*$/gm, '');

/** The text between the braces that open at `start` (the index of `{`), or null when they never close. */
function balanced(text, start) {
  let depth = 0;
  for (let i = start; i < text.length; i += 1) {
    if (text[i] === '{') depth += 1;
    else if (text[i] === '}') {
      depth -= 1;
      if (depth === 0) return text.slice(start + 1, i);
    }
  }
  return null;
}

const quoted = (text) =>
  [...text.matchAll(/'((?:\\.|[^'\\])*)'|"((?:\\.|[^"\\])*)"/g)].map(
    (m) => m[1] ?? m[2],
  );

/**
 * The `i18n` block of sites/<slug>/astro.config.mjs: { locales, defaultLocale, prefixDefaultLocale, problems }.
 * Returns null when the site has no `i18n` block (a single-language site). `problems` lists what could not be read
 * (the file is generated by `new-site --langs`, so this means someone changed it into something unexpected).
 */
export function readI18nConfig(siteDir) {
  const file = join(siteDir, 'astro.config.mjs');
  if (!existsSync(file)) return null;
  const text = stripLineComments(readFileSync(file, 'utf8'));
  const at = text.search(/\bi18n\s*:\s*\{/);
  if (at < 0) return null;
  const block = balanced(text, text.indexOf('{', at)) ?? '';
  const problems = [];
  const list = /\blocales\s*:\s*\[([\s\S]*?)\]/.exec(block);
  let locales = [];
  if (!list) problems.push('i18n.locales is not an array of strings');
  else {
    if (/[{}]/.test(list[1]))
      problems.push(
        'i18n.locales has custom path objects ({ path, codes }); use plain locale strings so the folder names match the locales',
      );
    locales = quoted(list[1]);
  }
  const def = /\bdefaultLocale\s*:\s*(?:'([^']*)'|"([^"]*)")/.exec(block);
  const defaultLocale = def ? (def[1] ?? def[2]) : '';
  if (!defaultLocale) problems.push('i18n.defaultLocale is not a string');
  else if (locales.length && !locales.includes(defaultLocale))
    problems.push(
      `i18n.defaultLocale "${defaultLocale}" is not in i18n.locales`,
    );
  const prefix = /\bprefixDefaultLocale\s*:\s*(true|false)/.exec(block);
  return {
    locales,
    defaultLocale,
    prefixDefaultLocale: prefix ? prefix[1] === 'true' : false,
    problems,
  };
}

/** The built file of a locale's home page, relative to dist/ (`index.html`, or `<locale>/index.html`). */
export const localeIndexFile = (config, locale) =>
  locale === config.defaultLocale && !config.prefixDefaultLocale
    ? 'index.html'
    : `${locale}/index.html`;

/** The locale a built page file (`es/privacidad/index.html`) belongs to, or the default locale. */
export function localeOfFile(config, file) {
  for (const locale of config.locales) {
    if (locale === config.defaultLocale && !config.prefixDefaultLocale)
      continue;
    if (file.startsWith(`${locale}/`)) return locale;
  }
  return config.defaultLocale;
}

/**
 * The UI dictionary of sites/<slug>/src/i18n/ui.ts as { locales: [...], strings: { es: { key: 'value' } } }, or null
 * when the file is missing. It reads the generated shape (`export const locales = [...]` and one object per locale in
 * `export const ui`); a value it cannot read is left out rather than guessed.
 */
export function readUiDictionary(siteDir) {
  const file = join(siteDir, 'src/i18n/ui.ts');
  if (!existsSync(file)) return null;
  const text = stripLineComments(readFileSync(file, 'utf8'));
  const list = /export\s+const\s+locales\s*=\s*\[([\s\S]*?)\]/.exec(text);
  const locales = list ? quoted(list[1]) : [];
  const strings = {};
  const start = text.search(/export\s+const\s+ui\b[^=]*=\s*\{/);
  const body =
    start < 0
      ? null
      : balanced(text, text.indexOf('{', text.indexOf('=', start)));
  if (body !== null) {
    const head =
      /(?:^|\n)\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z_$][\w$-]*))\s*:\s*\{/g;
    let match;
    while ((match = head.exec(body))) {
      const locale = match[1] ?? match[2] ?? match[3];
      const open = body.indexOf('{', match.index + match[0].length - 1);
      const inner = balanced(body, open) ?? '';
      strings[locale] = {};
      const entry =
        /(?:^|\n|,)\s*([A-Za-z_$][\w$]*)\s*:\s*(?:'((?:\\.|[^'\\])*)'|"((?:\\.|[^"\\])*)")/g;
      let item;
      while ((item = entry.exec(inner)))
        strings[locale][item[1]] = (item[2] ?? item[3]).replace(
          /\\(['"\\])/g,
          '$1',
        );
      head.lastIndex = open + inner.length + 2;
    }
  }
  return { locales, strings };
}

/** Attributes of an HTML tag string as an object (names lowercased). */
export function attributesOf(tag) {
  const attrs = {};
  for (const m of tag.matchAll(
    /([a-zA-Z_:][-\w:.]*)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+)))?/g,
  ))
    if (m.index > 0) attrs[m[1].toLowerCase()] = m[2] ?? m[3] ?? m[4] ?? '';
  return attrs;
}

/** The `<html lang>` of a built page, or '' when there is none. */
export const htmlLang = (html) =>
  /<html\b[^>]*\blang\s*=\s*(?:"([^"]*)"|'([^']*)')/i
    .exec(html)
    ?.slice(1)
    .find((v) => v !== undefined) ?? '';

/** `<link rel="alternate" hreflang href>` of a built page as [{ hreflang, href }]. */
export function alternatesOf(html) {
  return [...html.matchAll(/<link\b[^>]*>/gi)]
    .map((m) => attributesOf(m[0].slice(5)))
    .filter(
      (a) =>
        (a.rel ?? '').toLowerCase().split(/\s+/).includes('alternate') &&
        a.hreflang,
    )
    .map((a) => ({ hreflang: a.hreflang, href: a.href ?? '' }));
}

/** The href of `<link rel="canonical">`, or ''. */
export function canonicalOf(html) {
  for (const m of html.matchAll(/<link\b[^>]*>/gi)) {
    const a = attributesOf(m[0].slice(5));
    if ((a.rel ?? '').toLowerCase() === 'canonical') return a.href ?? '';
  }
  return '';
}

/**
 * The language switcher of a built page: `<nav ... data-language-switcher>` and its links as
 * [{ href, hreflang, current }], or null when the page has none.
 */
export function switcherOf(html) {
  const nav =
    /<nav\b[^>]*\bdata-language-switcher\b[^>]*>([\s\S]*?)<\/nav\s*>/i.exec(
      html,
    );
  if (!nav) return null;
  return [...nav[1].matchAll(/<a\b[^>]*>/gi)].map((m) => {
    const a = attributesOf(m[0].slice(2));
    return {
      href: a.href ?? '',
      hreflang: a.hreflang ?? '',
      current: 'aria-current' in a,
    };
  });
}
